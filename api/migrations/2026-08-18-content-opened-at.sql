-- 콘텐츠 '열기'와 AI '사용'을 구분한다. 부분환불 산식의 전제.
--
-- 왜: content_access는 AI 검토·서류대조·콘텐츠 열기 셋이 모두 같은 행에 기록해 왔다.
--     그래서 "AI만 쓰고 유료 본문은 한 번도 안 연" 이용자의 콘텐츠분을 돌려줄 수 없었다.
--     회생 완주 패키지 기준 89,000원 차이이고, 전자상거래법 제17조 제2항 제5호 단서가
--     보호하는 "제공이 개시되지 아니한 부분"이 정확히 그 몫이다.
--
-- first_access_at  : 패키지 이용 개시(AI 포함). 14일 자동환불 게이트는 계속 이 값을 쓴다.
-- content_opened_at: POST /api/content/open 으로 유료 본문을 실제로 연 시각. AI는 기록하지 않는다.
--
-- ⚠️ 기존 행은 NULL이 된다 = "콘텐츠를 연 기록이 확인되지 않음". 환불 계산에서는 이용자에게
--    유리한 쪽(콘텐츠분 환불 가능)으로 처리된다. 적용 시점에 기존 행은 관리자 테스트 1건뿐이었다.
--    소급해서 열람으로 단정하지 않는 것이 소비자보호 원칙에 맞다.
--
-- 되돌리기: SQLite는 DROP COLUMN이 제한적이다. 컬럼을 남겨 두고 코드에서 무시하는 편이 안전하다.
ALTER TABLE content_access ADD COLUMN content_opened_at INTEGER;
